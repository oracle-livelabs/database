COMMENT ON TABLE plants IS 'Fictional electronics assembly and test plants. Capacity is a daily unit snapshot, not a promise of available machine hours.';
COMMENT ON TABLE components IS 'Plant-specific electronic module revision, board material grade and assembly/test route. Purchased packaged semiconductors are traced as material lots. All costs are USD per unit.';
COMMENT ON TABLE customer_sites IS 'Synthetic electronic-device customer sites and their fulfillment contacts. LOCATION is the delivery point.';
COMMENT ON TABLE production_orders IS 'One production order belongs to one customer site and one plant. Scheduled dates are independent of quantities.';
COMMENT ON TABLE production_order_lines IS 'Component quantities planned at the order plant. LINE_TOTAL is quantity times unit cost.';
COMMENT ON COLUMN production_orders.order_total IS 'Sum of line material costs plus setup cost. This is planned manufacturing cost, not recognized revenue.';
COMMENT ON COLUMN production_order_lines.line_total IS 'Quantity times unit cost. Excludes order setup cost.';
COMMENT ON TABLE quality_observations IS 'Electrical test counts, rejected module percentages, rework and test downtime measured for synthetic module runs.';
COMMENT ON TABLE trace_entities IS 'Production orders, material lots, machines, suppliers, inspections, certificates and plants. Shared use does not prove a defect.';
COMMENT ON TABLE material_transfers IS 'Physical material movements between work centers. Cycles can represent rework.';

